import AppKit
import Foundation
import Observation

struct ClipboardItem: Identifiable, Equatable {
    let id = UUID()
    let text: String
    let timestamp: Date

    var preview: String {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmed.count > 60 {
            return String(trimmed.prefix(60)) + "…"
        }
        return trimmed
    }
}

@MainActor
protocol ClipboardPasteboard: AnyObject {
    var changeCount: Int { get }
    var types: [NSPasteboard.PasteboardType]? { get }
    var pasteboardItems: [NSPasteboardItem]? { get }
    func string(forType dataType: NSPasteboard.PasteboardType) -> String?
    @discardableResult
    func clearContents() -> Int
    @discardableResult
    func setString(_ string: String, forType dataType: NSPasteboard.PasteboardType) -> Bool
}

extension ClipboardPasteboard {
    var pasteboardItems: [NSPasteboardItem]? { nil }
}

extension NSPasteboard: ClipboardPasteboard {}

extension NSPasteboard.PasteboardType {
    static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
}

@MainActor
enum ClipboardPrivacyMarker {
    static let concealed = NSPasteboard.PasteboardType.concealedType
    static let transient = NSPasteboard.PasteboardType.transientType
    static let autoGenerated = NSPasteboard.PasteboardType.autoGeneratedType

    static let allMarkers: [NSPasteboard.PasteboardType] = [
        concealed,
        transient,
        autoGenerated
    ]

    private static let markerIdentifiers: Set<String> = [
        "org.nspasteboard.concealedtype",
        "org.nspasteboard.transienttype",
        "org.nspasteboard.autogeneratedtype"
    ]

    static func isSensitive(_ type: NSPasteboard.PasteboardType) -> Bool {
        markerIdentifiers.contains(type.rawValue.lowercased())
    }

    static func containsSensitiveMarker(in types: [NSPasteboard.PasteboardType]?) -> Bool {
        guard let types = types else { return false }
        return types.contains { isSensitive($0) }
    }

    static func containsSensitiveMarker(in pasteboard: any ClipboardPasteboard) -> Bool {
        if containsSensitiveMarker(in: pasteboard.types) {
            return true
        }

        if let items = pasteboard.pasteboardItems {
            for item in items {
                if containsSensitiveMarker(in: item.types) {
                    return true
                }
            }
        }

        if let nsPasteboard = pasteboard as? NSPasteboard {
            if nsPasteboard.availableType(from: allMarkers) != nil {
                return true
            }
        }

        return false
    }
}

@Observable @MainActor
final class ClipboardService {
    static let shared = ClipboardService()

    var history: [ClipboardItem] = []
    private(set) var pasteboard: any ClipboardPasteboard
    private var lastChangeCount: Int = 0
    private var pollTimer: Timer?

    init(pasteboard: any ClipboardPasteboard = NSPasteboard.general) {
        self.pasteboard = pasteboard
        self.lastChangeCount = pasteboard.changeCount
        if AppState.shared.settings.clipboardEnabled {
            checkClipboard()
            if NSClassFromString("XCTestCase") == nil {
                startPolling()
            }
        }
    }

    func setPasteboardForTesting(_ pasteboard: any ClipboardPasteboard) {
        self.pasteboard = pasteboard
        self.lastChangeCount = pasteboard.changeCount
    }

    func startPolling() {
        pollTimer?.invalidate()
        guard AppState.shared.settings.clipboardEnabled else { return }
        pollTimer = Timer.scheduledTimer(withTimeInterval: 1.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated {
                self?.checkClipboard()
            }
        }
    }

    func stopPolling() {
        pollTimer?.invalidate()
        pollTimer = nil
    }

    func checkClipboard() {
        guard AppState.shared.settings.clipboardEnabled else { return }
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        // Privacy hardening: Inspect pasteboard types before reading or storing text.
        // Content carrying Concealed, Transient, or AutoGenerated marker types must never be recorded.
        guard !ClipboardPrivacyMarker.containsSensitiveMarker(in: pasteboard) else {
            return
        }

        if let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            // Avoid duplicate if identical to top item
            if let first = history.first, first.text == string {
                return
            }

            let newItem = ClipboardItem(text: string, timestamp: Date())
            history.insert(newItem, at: 0)

            // Keep max 15 items
            if history.count > 15 {
                history.removeLast()
            }
            AMORAEventCenter.shared.emit(.clipboardUpdated)
        }
    }

    func copyToClipboard(_ item: ClipboardItem) {
        pasteboard.clearContents()
        pasteboard.setString(item.text, forType: .string)
        lastChangeCount = pasteboard.changeCount
        // Only a user-initiated restore reacts — never passive clipboard changes.
        AMORAEventCenter.shared.emit(.clipboardRestored)
    }

    func clearHistory() {
        history.removeAll()
    }
}
