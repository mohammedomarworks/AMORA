using AMORA.Orbit.Services.Contracts;
using AMORA.Orbit.Services.Implementations;
using AMORA.Orbit.ViewModels;
using Xunit;

namespace AMORA.Orbit.Tests;

public sealed class ClipboardHistoryTests
{
    [Fact]
    public async Task DisabledServiceNeverSubscribesOrReadsAndEnableDoesNotCaptureExistingClipboard()
    {
        var source = new FakeSource();
        using var service = new ClipboardHistoryService(source);
        await service.CaptureLatestAsync();
        Assert.Equal(0, source.Subscribers);
        Assert.Equal(0, source.Reads);
        service.SetEnabled(true);
        Assert.Equal(1, source.Subscribers);
        Assert.Equal(0, source.Reads);
        service.SetEnabled(false);
        Assert.Equal(0, source.Subscribers);
    }

    [Theory]
    [InlineData("org.nspasteboard.ConcealedType")]
    [InlineData("ORG.NSPASTEBOARD.TRANSIENTTYPE")]
    [InlineData("org.nspasteboard.AutoGeneratedType")]
    [InlineData("ExcludeClipboardContentFromMonitorProcessing")]
    [InlineData("CanIncludeInClipboardHistory")]
    [InlineData("CanUploadToCloudClipboard")]
    [InlineData("Clipboard Viewer Ignore")]
    public async Task PrivacyFormatsAreRejectedBeforeAnyTextRead(string format)
    {
        var content = new FakeContent("secret", new[] { "Text", format });
        var source = new FakeSource { Content = content };
        using var service = new ClipboardHistoryService(source);
        service.SetEnabled(true);
        await service.CaptureLatestAsync();
        Assert.Equal(0, content.TextReads);
        Assert.Empty(service.Entries);
    }

    [Fact]
    public async Task OrdinaryTextIsSessionOnlyDeduplicatedAndBoundedLikeMac()
    {
        var source = new FakeSource();
        using var service = new ClipboardHistoryService(source);
        service.SetEnabled(true);
        await service.CaptureLatestAsync();
        await service.CaptureLatestAsync();
        Assert.Single(service.Entries);
        for (int i = 0; i < 20; i++)
        {
            source.Content = new FakeContent("Item " + i);
            await service.CaptureLatestAsync();
        }
        Assert.Equal(15, service.Entries.Count);
        Assert.Equal("Item 19", service.Entries[0].Text);
        Assert.Equal("Item 5", service.Entries[^1].Text);
        using var freshSession = new ClipboardHistoryService(new FakeSource());
        Assert.Empty(freshSession.Entries);
        service.SetEnabled(false);
        Assert.Empty(service.Entries);
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public async Task DisableOrClearDuringPendingReadCannotRestoreClearedHistory(bool clear)
    {
        var pending = new TaskCompletionSource<string?>(TaskCreationOptions.RunContinuationsAsynchronously);
        var content = new FakeContent("ignored") { Pending = pending.Task };
        var source = new FakeSource { Content = content };
        using var service = new ClipboardHistoryService(source);
        service.SetEnabled(true);
        var capture = service.CaptureLatestAsync();
        Assert.Equal(1, content.TextReads);
        if (clear) service.Clear(); else service.SetEnabled(false);
        pending.SetResult("Never retain this after clear or disable");
        await capture;
        Assert.Empty(service.Entries);
    }

    [Fact]
    public async Task LateOldCaptureCannotOverwriteNewerClipboardState()
    {
        var pending = new TaskCompletionSource<string?>(TaskCreationOptions.RunContinuationsAsynchronously);
        var source = new FakeSource { Content = new FakeContent("ignored") { Pending = pending.Task } };
        using var service = new ClipboardHistoryService(source);
        service.SetEnabled(true);
        var old = service.CaptureLatestAsync();
        source.Content = new FakeContent("Newer text");
        await service.CaptureLatestAsync();
        pending.SetResult("Stale text");
        await old;
        Assert.Equal("Newer text", Assert.Single(service.Entries).Text);
    }

    [Theory]
    [InlineData("password=correct-horse-secret")]
    [InlineData("Authorization: Bearer abcdefghijklmnopqrstuvwxyz")]
    [InlineData("-----BEGIN RSA PRIVATE KEY-----")]
    [InlineData("sk-abcdefghijklmnopqrstuvwxyz123456")]
    [InlineData("bad\u0000control")]
    [InlineData("   ")]
    public void StructuredSecretsAndInvalidTextAreNotRetained(string text) => Assert.False(ClipboardPrivacyFilter.IsSafeText(text));

    [Fact]
    public void DiscussionOfPrivacyMarkersIsNotTreatedAsASecret()
    {
        Assert.True(ClipboardPrivacyFilter.IsSafeText("Password managers use org.nspasteboard.ConcealedType and TransientType."));
        Assert.False(ClipboardPrivacyFilter.IsSafeText(new string('a', ClipboardPrivacyFilter.MaxTextLength + 1)));
    }

    [Fact]
    public async Task ExplicitCopyRemoveAndClearUseKnownEntryOnly()
    {
        var source = new FakeSource();
        using var service = new ClipboardHistoryService(source);
        service.SetEnabled(true);
        await service.CaptureLatestAsync();
        var entry = Assert.Single(service.Entries);
        Assert.True(await service.CopyAsync(entry.Id));
        Assert.Equal(entry.Text, source.Written);
        Assert.False(await service.CopyAsync("unknown"));
        Assert.True(service.Remove(entry.Id));
        Assert.Empty(service.Entries);
        Assert.False(await service.CopyAsync(entry.Id));
        await service.CaptureLatestAsync();
        service.Clear();
        Assert.Empty(service.Entries);
    }

    [Fact]
    public async Task ClipboardFailuresAreSanitizedAndRecoveryContinues()
    {
        var source = new FakeSource { ThrowOnRead = true };
        using var service = new ClipboardHistoryService(source);
        service.SetEnabled(true);
        await service.CaptureLatestAsync();
        Assert.Contains("unavailable", service.StatusText);
        Assert.DoesNotContain("private-content", service.StatusText);
        Assert.Empty(service.Entries);
        source.ThrowOnRead = false;
        await service.CaptureLatestAsync();
        Assert.Single(service.Entries);
    }

    [Fact]
    public async Task ViewModelMarshalsHistoryAndDropsNotificationsAfterDisposal()
    {
        var source = new FakeSource();
        using var service = new ClipboardHistoryService(source);
        var queue = new Queue<Action>();
        using var vm = new ClipboardViewModel(service, queue.Enqueue);
        service.SetEnabled(true);
        await service.CaptureLatestAsync();
        Assert.Empty(vm.Entries);
        while (queue.TryDequeue(out var apply)) apply();
        Assert.Single(vm.Entries);
        source.Content = new FakeContent("Second");
        await service.CaptureLatestAsync();
        vm.Dispose();
        while (queue.TryDequeue(out var apply)) apply();
        Assert.Empty(vm.Entries);
    }

    private sealed class FakeContent(string text, IReadOnlyList<string>? formats = null) : IClipboardContentSnapshot
    {
        public IReadOnlyList<string> Formats => formats ?? new[] { "Text" };
        public bool HasText => true;
        public int TextReads { get; private set; }
        public Task<string?>? Pending { get; init; }
        public Task<string?> ReadTextAsync(CancellationToken cancellationToken)
        {
            TextReads++;
            return Pending ?? Task.FromResult<string?>(text);
        }
    }

    private sealed class FakeSource : IClipboardSource
    {
        private EventHandler? _changed;
        public int Subscribers { get; private set; }
        public int Reads { get; private set; }
        public string? Written { get; private set; }
        public bool ThrowOnRead { get; set; }
        public IClipboardContentSnapshot Content { get; set; } = new FakeContent("Ordinary copied text");
        public event EventHandler? ContentChanged
        {
            add { _changed += value; Subscribers++; }
            remove { _changed -= value; Subscribers--; }
        }
        public Task<IClipboardContentSnapshot?> GetSnapshotAsync(CancellationToken cancellationToken)
        {
            Reads++;
            if (ThrowOnRead) throw new IOException("private-content");
            return Task.FromResult<IClipboardContentSnapshot?>(Content);
        }
        public Task<bool> WriteTextAsync(string text, CancellationToken cancellationToken) { Written = text; return Task.FromResult(true); }
        public void Dispose() { _changed = null; }
    }
}
