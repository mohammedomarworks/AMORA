import AppKit
import XCTest
@testable import AMORA

@MainActor
final class MockPasteboard: ClipboardPasteboard {
    var changeCount: Int = 0
    var types: [NSPasteboard.PasteboardType]?
    var pasteboardItems: [NSPasteboardItem]?
    var didReadString: Bool = false
    private var storage: [NSPasteboard.PasteboardType: String] = [:]

    init(
        changeCount: Int = 0,
        types: [NSPasteboard.PasteboardType]? = nil,
        string: String? = nil,
        pasteboardItems: [NSPasteboardItem]? = nil
    ) {
        self.changeCount = changeCount
        self.types = types
        self.pasteboardItems = pasteboardItems
        if let string = string {
            self.storage[.string] = string
            if self.types == nil {
                self.types = [.string]
            }
        }
    }

    func string(forType dataType: NSPasteboard.PasteboardType) -> String? {
        didReadString = true
        return storage[dataType]
    }

    @discardableResult
    func clearContents() -> Int {
        changeCount += 1
        storage.removeAll()
        types = []
        pasteboardItems = []
        return changeCount
    }

    @discardableResult
    func setString(_ string: String, forType dataType: NSPasteboard.PasteboardType) -> Bool {
        storage[dataType] = string
        var currentTypes = types ?? []
        if !currentTypes.contains(dataType) {
            currentTypes.append(dataType)
        }
        types = currentTypes
        return true
    }

    func simulateCopy(
        text: String,
        types: [NSPasteboard.PasteboardType],
        items: [NSPasteboardItem]? = nil
    ) {
        changeCount += 1
        self.types = types
        self.pasteboardItems = items
        self.storage[.string] = text
        self.didReadString = false
    }
}

@MainActor
final class ClipboardPrivacyTests: XCTestCase {

    private var initialClipboardEnabled: Bool = true

    override func setUp() async throws {
        try await super.setUp()
        initialClipboardEnabled = AppState.shared.settings.clipboardEnabled
        AppState.shared.settings.clipboardEnabled = true
    }

    override func tearDown() async throws {
        AppState.shared.settings.clipboardEnabled = initialClipboardEnabled
        try await super.tearDown()
    }

    // MARK: - 1. Ordinary Text Capture

    func testOrdinaryTextIsCaptured() {
        let mock = MockPasteboard(changeCount: 0)
        let service = ClipboardService(pasteboard: mock)

        mock.simulateCopy(text: "Ordinary copied text", types: [.string])
        service.checkClipboard()

        XCTAssertEqual(service.history.count, 1)
        XCTAssertEqual(service.history.first?.text, "Ordinary copied text")
        XCTAssertTrue(mock.didReadString)
    }

    // MARK: - 2. Single Sensitive Markers

    func testConcealedMarkerIsSkippedAndNotRead() {
        let mock = MockPasteboard(changeCount: 0)
        let service = ClipboardService(pasteboard: mock)

        mock.simulateCopy(
            text: "super-secret-password-123",
            types: [.string, NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")]
        )
        service.checkClipboard()

        XCTAssertTrue(service.history.isEmpty, "Concealed clipboard content must never be recorded")
        XCTAssertFalse(mock.didReadString, "Concealed clipboard text must not be read into memory")
    }

    func testTransientMarkerIsSkippedAndNotRead() {
        let mock = MockPasteboard(changeCount: 0)
        let service = ClipboardService(pasteboard: mock)

        mock.simulateCopy(
            text: "one-time-totp-token-987654",
            types: [.string, NSPasteboard.PasteboardType("org.nspasteboard.TransientType")]
        )
        service.checkClipboard()

        XCTAssertTrue(service.history.isEmpty, "Transient clipboard content must never be recorded")
        XCTAssertFalse(mock.didReadString, "Transient clipboard text must not be read into memory")
    }

    func testAutoGeneratedMarkerIsSkippedAndNotRead() {
        let mock = MockPasteboard(changeCount: 0)
        let service = ClipboardService(pasteboard: mock)

        mock.simulateCopy(
            text: "autogenerated-secret-token",
            types: [.string, NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")]
        )
        service.checkClipboard()

        XCTAssertTrue(service.history.isEmpty, "Auto-generated clipboard content must never be recorded")
        XCTAssertFalse(mock.didReadString, "Auto-generated clipboard text must not be read into memory")
    }

    // MARK: - 3. Multiple Markers Combined

    func testMultipleMarkersTogetherAreSkipped() {
        let combinations: [[NSPasteboard.PasteboardType]] = [
            [NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"), NSPasteboard.PasteboardType("org.nspasteboard.TransientType")],
            [NSPasteboard.PasteboardType("org.nspasteboard.TransientType"), NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")],
            [NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"), NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")],
            [
                NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
                NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
                NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
            ]
        ]

        for (index, markers) in combinations.enumerated() {
            let mock = MockPasteboard(changeCount: index * 10)
            let service = ClipboardService(pasteboard: mock)

            var types: [NSPasteboard.PasteboardType] = [.string]
            types.append(contentsOf: markers)

            mock.simulateCopy(text: "sensitive-combo-\(index)", types: types)
            service.checkClipboard()

            XCTAssertTrue(
                service.history.isEmpty,
                "Content marked with combination \(markers.map(\.rawValue)) must not be recorded"
            )
            XCTAssertFalse(mock.didReadString, "Text must not be read when sensitive markers are present")
        }
    }

    // MARK: - 4. Case-Insensitive Matching

    func testCaseInsensitiveMarkerDetection() {
        let variants = [
            "org.nspasteboard.concealedtype",
            "org.nspasteboard.CONCEALEDTYPE",
            "org.nspasteboard.transienttype",
            "ORG.NSPASTEBOARD.TRANSIENTTYPE",
            "org.nspasteboard.autogeneratedtype",
            "Org.NSPasteboard.AutoGeneratedType"
        ]

        for (index, variant) in variants.enumerated() {
            let mock = MockPasteboard(changeCount: index * 5)
            let service = ClipboardService(pasteboard: mock)

            mock.simulateCopy(
                text: "password-\(variant)",
                types: [.string, NSPasteboard.PasteboardType(variant)]
            )
            service.checkClipboard()

            XCTAssertTrue(
                service.history.isEmpty,
                "Variant '\(variant)' must be detected regardless of case"
            )
            XCTAssertFalse(mock.didReadString)
        }
    }

    // MARK: - 5. Sensitive Marker on Pasteboard Item

    func testSensitiveMarkerOnPasteboardItemIsSkipped() {
        let mock = MockPasteboard(changeCount: 0)
        let service = ClipboardService(pasteboard: mock)

        let item = NSPasteboardItem()
        item.setString("item-level-secret", forType: .string)
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))

        // Simulate a scenario where pasteboard.types only shows .string, but the item has the marker
        mock.simulateCopy(
            text: "item-level-secret",
            types: [.string],
            items: [item]
        )
        service.checkClipboard()

        XCTAssertTrue(service.history.isEmpty, "Item-level sensitive marker must prevent clipboard capture")
        XCTAssertFalse(mock.didReadString)
    }

    // MARK: - 6. Polling & Repeated Checks

    func testRepeatedChecksAndPollingDoNotLeakSensitiveContent() {
        let mock = MockPasteboard(changeCount: 0)
        let service = ClipboardService(pasteboard: mock)

        mock.simulateCopy(
            text: "confidential-token",
            types: [.string, NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")]
        )

        // Multiple consecutive checks at the same changeCount
        service.checkClipboard()
        service.checkClipboard()
        service.checkClipboard()

        XCTAssertTrue(service.history.isEmpty)
        XCTAssertFalse(mock.didReadString)

        // Another sensitive copy at a new changeCount
        mock.simulateCopy(
            text: "another-sensitive-token",
            types: [.string, NSPasteboard.PasteboardType("org.nspasteboard.TransientType")]
        )
        service.checkClipboard()
        service.checkClipboard()

        XCTAssertTrue(service.history.isEmpty)
        XCTAssertFalse(mock.didReadString)
    }

    // MARK: - 7. Ordinary Text Interleaved with Sensitive Content

    func testOrdinaryTextInterleavedWithSensitiveContent() {
        let mock = MockPasteboard(changeCount: 0)
        let service = ClipboardService(pasteboard: mock)

        // 1. Copy sensitive password -> skipped
        mock.simulateCopy(
            text: "my-master-password",
            types: [.string, NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")]
        )
        service.checkClipboard()
        XCTAssertTrue(service.history.isEmpty)
        XCTAssertFalse(mock.didReadString)

        // 2. Copy ordinary text -> captured
        mock.simulateCopy(text: "https://example.com/docs", types: [.string])
        service.checkClipboard()
        XCTAssertEqual(service.history.count, 1)
        XCTAssertEqual(service.history.first?.text, "https://example.com/docs")
        XCTAssertTrue(mock.didReadString)

        // 3. Copy another sensitive item -> skipped, history unchanged
        mock.simulateCopy(
            text: "secret-api-key-999",
            types: [.string, NSPasteboard.PasteboardType("org.nspasteboard.TransientType")]
        )
        service.checkClipboard()
        XCTAssertEqual(service.history.count, 1)
        XCTAssertEqual(service.history.first?.text, "https://example.com/docs")

        // 4. Copy another ordinary item -> captured
        mock.simulateCopy(text: "swift build -c release", types: [.string])
        service.checkClipboard()
        XCTAssertEqual(service.history.count, 2)
        XCTAssertEqual(service.history[0].text, "swift build -c release")
        XCTAssertEqual(service.history[1].text, "https://example.com/docs")
    }

    // MARK: - 8. Keyword Invariance (No False Positives)

    func testTextWithSensitiveKeywordsInContentIsCapturedWhenMarkersAbsent() {
        let mock = MockPasteboard(changeCount: 0)
        let service = ClipboardService(pasteboard: mock)

        let codeSnippet = """
        // Password managers use org.nspasteboard.ConcealedType and TransientType
        let concealed = "org.nspasteboard.ConcealedType"
        """

        mock.simulateCopy(text: codeSnippet, types: [.string])
        service.checkClipboard()

        XCTAssertEqual(service.history.count, 1)
        XCTAssertEqual(service.history.first?.text, codeSnippet)
    }

    // MARK: - 9. Deduplication & Capacity Limit

    func testDeduplicationAndCapacityLimitPreserved() {
        let mock = MockPasteboard(changeCount: 0)
        let service = ClipboardService(pasteboard: mock)

        // Duplicate copies
        mock.simulateCopy(text: "repeated text", types: [.string])
        service.checkClipboard()
        XCTAssertEqual(service.history.count, 1)

        mock.simulateCopy(text: "repeated text", types: [.string])
        service.checkClipboard()
        XCTAssertEqual(service.history.count, 1, "Duplicate text must not be inserted consecutively")

        // Capacity limit: max 15 items
        for i in 1...20 {
            mock.simulateCopy(text: "item-\(i)", types: [.string])
            service.checkClipboard()
        }
        XCTAssertEqual(service.history.count, 15)
        XCTAssertEqual(service.history.first?.text, "item-20")
    }

    // MARK: - 10. Copy To Clipboard (Restore)

    func testCopyToClipboardUpdatesPasteboardAndAlignsChangeCount() {
        let mock = MockPasteboard(changeCount: 0)
        let service = ClipboardService(pasteboard: mock)

        mock.simulateCopy(text: "Saved Note", types: [.string])
        service.checkClipboard()
        XCTAssertEqual(service.history.count, 1)

        let itemToRestore = service.history[0]
        service.copyToClipboard(itemToRestore)

        XCTAssertEqual(mock.string(forType: .string), "Saved Note")

        // Subsequent checkClipboard() must not duplicate the item AMORA just wrote
        service.checkClipboard()
        XCTAssertEqual(service.history.count, 1)
    }

    // MARK: - 11. Clipboard Disabled Setting

    func testClipboardDisabledSuppressesCapture() {
        AppState.shared.settings.clipboardEnabled = false
        let mock = MockPasteboard(changeCount: 0)
        let service = ClipboardService(pasteboard: mock)

        mock.simulateCopy(text: "Should not be recorded", types: [.string])
        service.checkClipboard()

        XCTAssertTrue(service.history.isEmpty)
        XCTAssertFalse(mock.didReadString)
    }
}
